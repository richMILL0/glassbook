CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(16)  NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE trading_order (
    id              BIGINT       PRIMARY KEY,
    participant_id  BIGINT       NOT NULL,
    instrument_id   INTEGER      NOT NULL,
    symbol          VARCHAR(16)  NOT NULL,
    client_order_id VARCHAR(64),
    side            VARCHAR(8)   NOT NULL,
    order_type      VARCHAR(8)   NOT NULL,
    time_in_force   VARCHAR(16)  NOT NULL,
    price           BIGINT       NOT NULL,
    quantity        BIGINT       NOT NULL,
    filled_quantity BIGINT       NOT NULL,
    status          VARCHAR(24)  NOT NULL,
    cancel_reason   VARCHAR(32),
    created_seq     BIGINT       NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_order_participant ON trading_order (participant_id, id);

CREATE TABLE trade (
    id            BIGINT      PRIMARY KEY,
    seq           BIGINT      NOT NULL,
    instrument_id INTEGER     NOT NULL,
    symbol        VARCHAR(16) NOT NULL,
    price         BIGINT      NOT NULL,
    quantity      BIGINT      NOT NULL,
    buy_order_id  BIGINT      NOT NULL,
    sell_order_id BIGINT      NOT NULL,
    buyer_id      BIGINT      NOT NULL,
    seller_id     BIGINT      NOT NULL,
    taker_side    VARCHAR(8)  NOT NULL,
    executed_at   TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_trade_instrument ON trade (instrument_id, id);
CREATE INDEX ix_trade_buyer ON trade (buyer_id, id);
CREATE INDEX ix_trade_seller ON trade (seller_id, id);

CREATE TABLE ledger_entry (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seq        BIGINT      NOT NULL,
    account_id BIGINT      NOT NULL,
    asset_id   INTEGER     NOT NULL,
    delta      BIGINT      NOT NULL,
    kind       VARCHAR(16) NOT NULL,
    ref_id     BIGINT      NOT NULL,
    posted_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_ledger_account ON ledger_entry (account_id, id);
CREATE INDEX ix_ledger_seq ON ledger_entry (seq);

CREATE TABLE outbox (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic        VARCHAR(64)   NOT NULL,
    event_key    VARCHAR(64)   NOT NULL,
    payload      VARCHAR(4000) NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_outbox_pending ON outbox (published_at, id);

CREATE TABLE projection_cursor (
    id       INTEGER PRIMARY KEY,
    last_seq BIGINT  NOT NULL
);
